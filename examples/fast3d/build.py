"""Builds the fast3d benchmark for retro-z80 (examples/fast3d/README.md):
the tables from model.py, the screen's row table and draw_line's blocks for
retro-z80's linear 1 bpp screen, the models and the world, into output/;
then sjasmplus on fast3d.asm, for build/fast3d.bin and .sld, loaded at 0x8000.

    python build.py              # the software engine, frame times only
    python build.py --phases     # the same, timing each part of the frame
    python build.py --geom       # culling and vertices through the geometry unit
    python build.py --geom --phases
    python build.py [--geom] --faces [--phases]   # each object losing its back edges
    python build.py --line [--phases]   # lines by the DMA engine (spec 14, LINE)
    python build.py [...] --dmaclear     # the last picture cleared by a DMA fill

Every build runs the CPU at 3.57 MHz (CPUSPEED.SPECTRUM), as a Spectrum;
--20mhz runs it at 20 MHz instead, with _20mhz on the name.

Copied from zx-spectrum-emulator's examples/fast3d/build.py (commit
1534bc5). Changed: the screen (screen_address, write_rows, write_lines), and
main; the check builds, check models and the snapshot are left out.
"""
